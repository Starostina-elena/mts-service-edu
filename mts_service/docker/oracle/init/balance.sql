DECLARE
  cnt NUMBER := 0;
BEGIN
  SELECT COUNT(*) INTO cnt FROM ALL_TABLES WHERE OWNER = 'APP_USER' AND TABLE_NAME = 'BALANCE';
  IF cnt = 0 THEN
    EXECUTE IMMEDIATE q'[CREATE TABLE APP_USER.BALANCE (
      ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
      USER_ID NUMBER NOT NULL,
      AMOUNT NUMBER(19,2) DEFAULT 0 NOT NULL,
      CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
      UPDATED_AT TIMESTAMP
    )]';
  END IF;
END;
/
DECLARE
  cnt NUMBER := 0;
BEGIN
  BEGIN
    SELECT COUNT(*) INTO cnt FROM APP_USER.BALANCE;
  EXCEPTION WHEN OTHERS THEN
    cnt := 0;
  END;
  IF cnt = 0 THEN
    EXECUTE IMMEDIATE 'INSERT INTO APP_USER.BALANCE (USER_ID, AMOUNT) VALUES (1, 0)';
    COMMIT;
  END IF;
END;
