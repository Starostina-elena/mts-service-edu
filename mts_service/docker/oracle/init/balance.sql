   BEGIN
     EXECUTE IMMEDIATE 'CREATE USER app_user IDENTIFIED BY app_user';
   EXCEPTION
     WHEN OTHERS THEN
       IF SQLCODE != -01920 THEN
         RAISE;
       END IF;
   END;

   BEGIN
     EXECUTE IMMEDIATE 'GRANT CONNECT, RESOURCE, CREATE TABLE TO app_user';
   EXCEPTION
     WHEN OTHERS THEN
       NULL;
   END;
END;
